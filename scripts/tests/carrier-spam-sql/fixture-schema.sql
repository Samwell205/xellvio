CREATE SCHEMA pgmq;
CREATE TABLE pgmq.test_queue(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, queue_name text, payload jsonb);
CREATE FUNCTION pgmq.send(queue_name text, msg jsonb) RETURNS bigint LANGUAGE plpgsql AS $$ DECLARE result bigint; BEGIN INSERT INTO pgmq.test_queue(queue_name,payload) VALUES(queue_name,msg) RETURNING id INTO result; RETURN result; END $$;
