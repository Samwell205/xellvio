CREATE TABLE public.support_tickets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) UNIQUE,
  account_id uuid,
  requester_email text NOT NULL,
  requester_name text,
  subject text NOT NULL DEFAULT 'Support request',
  topic text,
  source text NOT NULL DEFAULT 'contact',
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','waiting','closed')),
  access_token text NOT NULL UNIQUE DEFAULT encode(extensions.gen_random_bytes(24), 'hex'),
  previous_ticket_id uuid REFERENCES public.support_tickets(id) ON DELETE SET NULL,
  legacy_contact_id uuid UNIQUE,
  last_admin_reply_at timestamptz,
  last_customer_reply_at timestamptz,
  reminder_sent_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX support_tickets_status_idx ON public.support_tickets(status, updated_at DESC);
CREATE INDEX support_tickets_account_idx ON public.support_tickets(account_id, created_at DESC);
CREATE INDEX support_tickets_email_idx ON public.support_tickets(lower(requester_email));

CREATE TABLE public.support_ticket_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id uuid NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
  author text NOT NULL CHECK (author IN ('customer','admin','system')),
  author_user_id uuid,
  body text NOT NULL,
  internal boolean NOT NULL DEFAULT false,
  via text NOT NULL DEFAULT 'web',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX support_ticket_messages_ticket_idx ON public.support_ticket_messages(ticket_id, created_at);

GRANT SELECT ON public.support_tickets TO authenticated;
GRANT SELECT ON public.support_ticket_messages TO authenticated;
GRANT ALL ON public.support_tickets TO service_role;
GRANT ALL ON public.support_ticket_messages TO service_role;

ALTER TABLE public.support_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_ticket_messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admins read tickets" ON public.support_tickets FOR SELECT TO authenticated
  USING (public.has_role('admin'::public.app_role));
CREATE POLICY "Tenants read own tickets" ON public.support_tickets FOR SELECT TO authenticated
  USING (account_id = public.get_acting_account_id(auth.uid()));
CREATE POLICY "Admins read ticket messages" ON public.support_ticket_messages FOR SELECT TO authenticated
  USING (public.has_role('admin'::public.app_role));
CREATE POLICY "Tenants read own public ticket messages" ON public.support_ticket_messages FOR SELECT TO authenticated
  USING (NOT internal AND EXISTS (SELECT 1 FROM public.support_tickets t WHERE t.id = ticket_id AND t.account_id = public.get_acting_account_id(auth.uid())));

-- Backfill: existing contact-form messages become tickets.
INSERT INTO public.support_tickets (requester_email, requester_name, subject, topic, source, status, legacy_contact_id, last_customer_reply_at, created_at, updated_at, account_id, closed_at)
SELECT m.email, m.name, m.topic, m.topic, 'contact',
  CASE WHEN m.status = 'new' THEN 'open' ELSE 'closed' END,
  m.id, m.created_at, m.created_at, m.created_at,
  (SELECT a.id FROM public.accounts a WHERE lower(a.email) = lower(m.email) LIMIT 1),
  CASE WHEN m.status = 'new' THEN NULL ELSE m.created_at END
FROM public.contact_messages m ORDER BY m.created_at;
INSERT INTO public.support_ticket_messages (ticket_id, author, body, created_at, via)
SELECT t.id, 'customer', m.message, m.created_at, 'contact'
FROM public.contact_messages m JOIN public.support_tickets t ON t.legacy_contact_id = m.id;
COMMENT ON TABLE public.contact_messages IS 'DEPRECATED: contact submissions now create support_tickets';